$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$assets = Join-Path $projectRoot 'src\main\resources\assets\guerra_ezuberante'
$pt = Get-Content -LiteralPath (Join-Path $assets 'lang\pt_br.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$en = Get-Content -LiteralPath (Join-Path $assets 'lang\en_us.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$difference = Compare-Object ($pt.PSObject.Properties.Name | Sort-Object) ($en.PSObject.Properties.Name | Sort-Object)
if ($difference) { throw 'As traduções pt_br e en_us possuem chaves diferentes.' }

foreach ($skin in @(
    @{ Texture = 'renan_santos'; Source = 'renan_santos_skin_64x64.png' },
    @{ Texture = 'arthur_do_val'; Source = 'arthur_do_val_skin_64x64_corrigida.png' },
    @{ Texture = 'combatente_ucraniana'; Source = 'skin-loira.png' },
    @{ Texture = 'haddad'; Source = 'haddad_skin_64x64_refatorada.png' },
    @{ Texture = 'guilherme_boulos'; Source = 'guilherme_boulos_skin_64x64.png' },
    @{ Texture = 'dilma'; Source = 'dilma_skin_64x64_refatorada.png' },
    @{ Texture = 'jones_manoel'; Source = 'jones_manoel_skin_64x64_refatorada.png' },
    @{ Texture = 'tabata_amaral'; Source = 'tabata_amaral_skin_64x64_refatorada.png' },
    @{ Texture = 'marina_silva'; Source = 'marina_silva_skin_64x64_refatorada.png' },
    @{ Texture = 'ciro_gomes'; Source = 'ciro_gomes_skin_64x64.png' },
    @{ Texture = 'comunista\comunista_0'; Source = 'comunistas\comunista_0.png' },
    @{ Texture = 'comunista\comunista_1'; Source = 'comunistas\comunista_1.png' },
    @{ Texture = 'comunista\comunista_2'; Source = 'comunistas\comunista_2.png' },
    @{ Texture = 'comunista\comunista_3'; Source = 'comunistas\comunista_3.png' },
    @{ Texture = 'bolsonarista\bolsonarista_0'; Source = 'bolsonaristas\bolsonarista_0.png' },
    @{ Texture = 'bolsonarista\bolsonarista_1'; Source = 'bolsonaristas\bolsonarista_1_corrigida.png' },
    @{ Texture = 'bolsonarista\bolsonarista_2'; Source = 'bolsonaristas\bolsonarista_2.png' },
    @{ Texture = 'bolsonarista\bolsonarista_3'; Source = 'bolsonaristas\bolsonarista_3.png' },
    @{ Texture = 'bolsonarista\bolsonarista_4'; Source = 'bolsonaristas\bolsonarista_4_corrigida.png' },
    @{ Texture = 'eneias'; Source = 'eneias_skin_64x64.png' },
    @{ Texture = 'augusto_cury'; Source = 'augusto_cury_skin_64x64.png' },
    # 0.022: generated by tools/GenerateZemaCaiadoSkins.java, no outside source.
    @{ Texture = 'romeu_zema' },
    @{ Texture = 'ronaldo_caiado' },
    @{ Texture = 'direitista\direitista_0' },
    @{ Texture = 'direitista\direitista_1' },
    @{ Texture = 'direitista\direitista_2' },
    @{ Texture = 'direitista\direitista_3' },
    @{ Texture = 'direitista\direitista_4' },
    @{ Texture = 'traficante_de_armas'; Source = 'traficante_de_armas_skin_64x64.png' },
    @{ Texture = 'petista\petista_0'; Source = 'petistas\petista_0.png' },
    @{ Texture = 'petista\petista_1'; Source = 'petistas\petista_1.png' },
    @{ Texture = 'petista\petista_2' },
    @{ Texture = 'petista\petista_3'; Source = 'petistas\petista_3.png' },
    @{ Texture = 'petista\petista_4'; Source = 'petistas\petista_4.png' },
    @{ Texture = 'petista\petista_5'; Source = 'petistas\petista_5.png' }
)) {
    $skinPath = Join-Path $assets ('textures\entity\' + $skin.Texture + '.png')
    $bytes = [IO.File]::ReadAllBytes($skinPath)
    if ($bytes.Length -lt 24 -or [BitConverter]::ToString($bytes, 0, 8) -ne '89-50-4E-47-0D-0A-1A-0A') {
        throw "PNG inválido: $skinPath"
    }
    $widthBytes = [byte[]]$bytes[16..19]
    $heightBytes = [byte[]]$bytes[20..23]
    [Array]::Reverse($widthBytes)
    [Array]::Reverse($heightBytes)
    if ([BitConverter]::ToInt32($widthBytes, 0) -ne 64 -or [BitConverter]::ToInt32($heightBytes, 0) -ne 64) {
        throw "A skin deve ter 64 x 64 pixels: $skinPath"
    }
    # 0.022.3 keeps the original sources intact and validates the new native pixel-art source copies instead.
    $refactoredSource = Join-Path $projectRoot ('assets-entrada\skins\refatoracao-8\' + [IO.Path]::GetFileName($skin.Texture) + '_skin_64x64.png')
    if (Test-Path -LiteralPath $refactoredSource) {
        if ((Get-FileHash -LiteralPath $refactoredSource).Hash -ne (Get-FileHash -LiteralPath $skinPath).Hash) {
            throw "Skin refatorada e recurso diferentes: $skinPath"
        }
        continue
    }
    # Historical sources for unchanged characters remain byte-identical.
    if (-not $skin.Source) { continue }
    $source = Join-Path $projectRoot ('assets-entrada\skins\' + $skin.Source)
    if ((Test-Path -LiteralPath $source) -and
        (Get-FileHash -LiteralPath $source).Hash -ne (Get-FileHash -LiteralPath $skinPath).Hash) {
        throw "Skin fonte e recurso diferentes: $skinPath"
    }
}
$swordPath = Join-Path $assets 'textures\item\espada_ucraniana.png'
$sword = [IO.File]::ReadAllBytes($swordPath)
if ([BitConverter]::ToString($sword, 0, 8) -ne '89-50-4E-47-0D-0A-1A-0A' -or
    [BitConverter]::ToString($sword, 16, 8) -ne '00-00-00-10-00-00-00-10') { throw 'A espada deve ser PNG 16 x 16.' }
$swordSource = Join-Path $projectRoot 'assets-entrada\texturas\espada_bandeira_ucrania_16x16.png'
if ((Get-FileHash -LiteralPath $swordSource).Hash -ne (Get-FileHash -LiteralPath $swordPath).Hash) {
    throw 'A textura da espada deve preservar o sprite original.'
}
$paintingTag = Get-Content -LiteralPath (Join-Path $projectRoot 'src\main\resources\data\minecraft\tags\painting_variant\placeable.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$paintingSpecs = @(
    @{ Prefix = '01'; Id = 'feliz_datas'; Width = 512; Height = 256 },
    @{ Prefix = '02'; Id = 'happy_nation'; Width = 512; Height = 256 },
    @{ Prefix = '03'; Id = 'me_respeita'; Width = 512; Height = 512 },
    @{ Prefix = '04'; Id = 'pergunta'; Width = 256; Height = 256 },
    @{ Prefix = '05'; Id = 'rachadinha_tres_porcento'; Width = 256; Height = 256 },
    @{ Prefix = '06'; Id = 'sacos_lula_flavio'; Width = 512; Height = 512 },
    @{ Prefix = '07'; Id = 'mestre_dos_bagos'; Width = 256; Height = 384 },
    @{ Prefix = '08'; Id = 'bolsonaro_joinha'; Width = 256; Height = 256 },
    @{ Prefix = '09'; Id = 'um_pau'; Width = 512; Height = 256 },
    @{ Prefix = '10'; Id = 'tweet_autodeclaracao'; Width = 512; Height = 384 }
)
foreach ($painting in $paintingSpecs) {
    $sources = @(Get-ChildItem -LiteralPath (Join-Path $projectRoot 'assets-entrada\quadros') -File | Where-Object {
        $_.BaseName.StartsWith($painting.Prefix) -and $_.Extension.ToLowerInvariant() -in @('.png', '.jpg', '.jpeg')
    })
    if ($sources.Count -ne 1) { throw "Imagem-fonte ausente ou duplicada para o quadro $($painting.Id)." }
    $texture = Join-Path $assets ('textures\painting\' + $painting.Id + '.png')
    $bytes = [IO.File]::ReadAllBytes($texture)
    if ($bytes.Length -lt 24 -or [BitConverter]::ToString($bytes, 0, 8) -ne '89-50-4E-47-0D-0A-1A-0A') {
        throw "PNG de quadro inválido: $texture"
    }
    $widthBytes = [byte[]]$bytes[16..19]; [Array]::Reverse($widthBytes)
    $heightBytes = [byte[]]$bytes[20..23]; [Array]::Reverse($heightBytes)
    if ([BitConverter]::ToInt32($widthBytes, 0) -ne $painting.Width -or
        [BitConverter]::ToInt32($heightBytes, 0) -ne $painting.Height) {
        throw "Dimensão incorreta para o quadro $($painting.Id)."
    }
    if ($paintingTag.values -notcontains ('guerra_ezuberante:' + $painting.Id)) {
        throw "Quadro fora da tag placeable: $($painting.Id)"
    }
}
if (@($paintingTag.values | Where-Object { $_ -like 'guerra_ezuberante:*' }).Count -ne 10) {
    throw 'A tag placeable deve conter exatamente os dez quadros do mod.'
}
$sounds = Get-Content -LiteralPath (Join-Path $assets 'sounds.json') -Raw -Encoding UTF8 | ConvertFrom-Json
foreach ($event in $sounds.PSObject.Properties) {
    if (-not $pt.PSObject.Properties[$event.Value.subtitle]) { throw "Legenda ausente: $($event.Value.subtitle)" }
    foreach ($sound in $event.Value.sounds) {
        $name = if ($sound -is [string]) { $sound } else { $sound.name }
        $relative = $name -replace '^guerra_ezuberante:', ''
        $file = Join-Path $assets ('sounds\' + $relative + '.ogg')
        if (-not (Test-Path -LiteralPath $file)) { throw "OGG ausente: $file" }
        $header = [IO.File]::ReadAllBytes($file)
        if ($header.Length -lt 4 -or [Text.Encoding]::ASCII.GetString($header, 0, 4) -ne 'OggS') {
            throw "Cabeçalho OGG inválido: $file"
        }
    }
}
Get-ChildItem -LiteralPath (Join-Path $projectRoot 'src\main\resources') -Filter '*.json' -Recurse |
    ForEach-Object { Get-Content -LiteralPath $_.FullName -Raw -Encoding UTF8 | ConvertFrom-Json | Out-Null }
Write-Host 'OK: JSONs, traduções, legendas, OGGs, skins e 10 quadros preservados.'
